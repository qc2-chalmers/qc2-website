#!/usr/bin/env python3
"""Build the website pages from ``pages/`` and the reusable components in ``components/``.

Every page in ``pages/`` is a complete HTML document, except that the blocks
shared by all pages are replaced by a marker:

    <!-- include: header -->                    the navigation bar
    <!-- include: header active=blog.html -->   ...with "News" highlighted
    <!-- include: footer -->                    the "Supported by" footer

The marker is swapped for ``components/<name>.html`` and the result is written to
the site root (``pages/blog.html`` -> ``blog.html``). The navigation link that
points to the page itself (or to ``active=``) is highlighted automatically.

The generated pages are not committed (see .gitignore): Vercel runs this script
on every deployment (vercel.json). To preview locally:

    uv run scripts/build_pages.py        # or: python3 scripts/build_pages.py
    python3 -m http.server               # then open http://localhost:8000

Only the Python standard library is used.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGES = ROOT / "pages"
COMPONENTS = ROOT / "components"

INCLUDE = re.compile(r"^([ \t]*)<!--\s*include:\s*([\w-]+)((?:\s+[\w-]+=\S+)*)\s*-->[ \t]*$", re.M)
BANNER = "<!-- Generated by scripts/build_pages.py from pages/{name} - edit that file, not this one. -->\n"


def _link(target: str) -> re.Pattern:
    return re.compile(rf'<a class="(?:nav-link py-2 px-lg-2|dropdown-item)" href="{re.escape(target)}"')


def highlight(html: str, target: str) -> str:
    """Mark the menu link pointing to ``target`` as the current page.

    Links inside a dropdown group also flag their group as ``has-current``.
    """
    m = _link(target).search(html)
    pos = m.end()
    html = html[:pos] + ' aria-current="page"' + html[pos:]
    if 'class="dropdown-item"' in m.group(0):
        start = html.rfind('nav-group"', 0, m.start())
        html = html[:start] + 'nav-group has-current"' + html[start + len('nav-group"'):]
    return html


def has_menu_link(html: str, target: str) -> bool:
    return _link(target).search(html) is not None


def render(page: Path) -> str:
    text = page.read_text(encoding="utf-8")

    def expand(match: re.Match) -> str:
        _, name, raw_args = match.groups()
        args = dict(a.split("=", 1) for a in raw_args.split())
        component = COMPONENTS / f"{name}.html"
        if not component.exists():
            raise ValueError(f"{page.name}: unknown include {name!r}")
        html = component.read_text(encoding="utf-8").rstrip("\n")
        if name == "header":
            target = args.get("active", page.name)
            if has_menu_link(html, target):
                html = highlight(html, target)
            elif "active" in args:
                raise ValueError(f"{page.name}: no navigation link to {target!r}")
        return html  # components already carry their own indentation

    text = INCLUDE.sub(expand, text)
    leftover = re.search(r"<!--\s*include:", text)
    if leftover:
        raise ValueError(f"{page.name}: malformed include near {text[leftover.start():leftover.start() + 60]!r}")

    first_line_end = text.find("\n") + 1  # keep <!doctype html> as the very first line
    return text[:first_line_end] + BANNER.format(name=page.name) + text[first_line_end:]


def main() -> int:
    sources = sorted(PAGES.glob("*.html"))
    if not sources:
        print(f"no pages found in {PAGES}", file=sys.stderr)
        return 1
    try:
        for page in sources:
            with open(ROOT / page.name, "w", encoding="utf-8", newline="\n") as out:
                out.write(render(page))
    except ValueError as err:
        print(f"build failed: {err}", file=sys.stderr)
        return 1
    print(f"built {len(sources)} pages: {', '.join(p.name for p in sources)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
